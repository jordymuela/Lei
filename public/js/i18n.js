const DICTS = { en, pt, es };

/**
 * Returns a translator for `lang` ("pt-BR", "es-MX", "en"…): t(key, vars) fills {placeholders}.
 * @param {string | null | undefined} lang
 */
export function makeT(lang) {
  const code = (lang || navigator.language || "en").slice(0, 2).toLowerCase();
  const dict = DICTS[code] || en;
  const t = (key, vars = {}) => (dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  t.lang = DICTS[code] ? code : "en";
  return t;
}

/** Fills every [data-i18n] element's text (and [data-i18n-label] aria-labels) from `t`. */
export function translatePage(t) {
  document.documentElement.lang = t.lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-label]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nLabel)));
}
